#!/bin/bash
# check-api-copies.sh OUT ORIGINAL... -- COPY...: the build rule decode_api_copies_check (Android.bp). Every copy of
# the decode service's API (an AIDL file or DecodeChecks.java, in MediaProvider and the other callers that keep one)
# must be byte for byte the original of the same name, and every original must have its copy. Writes OUT, an empty
# class the client library compiles, only when all match, so a copy that drifts fails the build.
set -u
out=${1:?out}
shift
originals=()
while [ $# -gt 0 ] && [ "$1" != -- ]; do originals+=("$1"); shift; done
[ "${1:-}" = -- ] && shift
copies=("$@")
rc=0
for o in "${originals[@]}"; do
  name=$(basename "$o")
  found=0
  for c in "${copies[@]}"; do
    [ "$(basename "$c")" = "$name" ] || continue
    found=$((found + 1))
    if ! cmp -s "$o" "$c"; then
      echo "decode service API copy differs from the original: $c (original $o)" >&2
      diff -u "$o" "$c" | head -n 40 >&2
      rc=1
    fi
  done
  [ $found -ge 1 ] || { echo "decode service API copy missing: $name" >&2; rc=1; }
done
for c in "${copies[@]}"; do
  name=$(basename "$c")
  match=0
  for o in "${originals[@]}"; do [ "$(basename "$o")" = "$name" ] && match=1; done
  [ $match = 1 ] || { echo "decode service API copy without an original: $c" >&2; rc=1; }
done
[ $rc = 0 ] || exit 1
cat > "$out" <<'JAVA'
package de.diamaneos.sanitizer.decode;

/** Generated by tools/check-api-copies.sh: the callers' copies of this API matched it at build time. */
final class ApiCopiesChecked {
    private ApiCopiesChecked() {
    }
}
JAVA
